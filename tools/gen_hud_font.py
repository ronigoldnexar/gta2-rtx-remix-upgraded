#!/usr/bin/env python3
"""Embeds the modern HUD's typeface in the DLL (dll/src/hud3d_font.inc).

Source: Barlow Condensed (SIL Open Font License 1.1, assets/fonts/OFL-BarlowCondensed.txt,
https://github.com/jpt/barlow), three styles subset to Latin-1 plus a few typographic
marks with fontTools:

  pyftsubset BarlowCondensed-<Style>.ttf --unicodes="U+0020-007E,U+00A0-00FF,U+2013,U+2014,
      U+2019,U+201C,U+201D,U+2022,U+2026" --layout-features=kern --no-hinting \
      --desubroutinize --output-file=assets/fonts/BarlowCondensed-<Style>-hud.ttf

Run from the repository root: python3 tools/gen_hud_font.py
"""
import os

FONTS = [("kHudFontHeavy", "BarlowCondensed-ExtraBoldItalic-hud.ttf"),
         ("kHudFontBold", "BarlowCondensed-BoldItalic-hud.ttf"),
         ("kHudFontText", "BarlowCondensed-SemiBold-hud.ttf")]

def main():
    out = ["// Generated by tools/gen_hud_font.py from assets/fonts (Barlow Condensed, SIL OFL 1.1).",
           "// Do not edit by hand.", "#pragma once", ""]
    for name, fn in FONTS:
        data = open(os.path.join("assets", "fonts", fn), "rb").read()
        out.append(f"// {fn}, {len(data)} bytes")
        out.append(f"alignas(4) static const unsigned char {name}[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            out.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        out.append("};")
        out.append("")
    open(os.path.join("dll", "src", "hud3d_font.inc"), "w").write("\n".join(out))

if __name__ == "__main__":
    main()
