#!/usr/bin/env bash
# Compiles src/shaders/visuals.hlsl into src/shaders/visuals_gen.h (shader model 3 bytecode
# as DWORD arrays), so the DLL carries its shaders and needs no compiler at run time.
#
# HLSL -> D3D9 bytecode needs a d3dcompiler: Wine 10's (vkd3d-shader) handles loops and
# ps_3_0; Wine 9's does not. Runs tools/shc.exe (tools/shc.cpp, MinGW) in the gta2-wine2510
# image (Ubuntu 25.10, Wine 10). On Windows, fxc.exe /T ps_3_0 /E <entry> gives the same.
#   tools/build_shaders.sh            (from the repository root)
set -e
cd "$(dirname "$0")/.."
WORK=$(mktemp -d)
i686-w64-mingw32-g++ -O1 -static -o "$WORK/shc.exe" tools/shc.cpp
cp src/shaders/visuals.hlsl "$WORK/"
ENTRIES="vs_shadow_world:vs_3_0 vs_shadow_model:vs_3_0 ps_shadow_world:ps_3_0 ps_shadow_solid:ps_3_0 ps_shadow_cutout:ps_3_0
vs_quad:vs_3_0 ps_composite:ps_3_0 ps_ssao8:ps_3_0 ps_ssao12:ps_3_0 ps_ao_blur:ps_3_0 vs_light:vs_3_0 ps_light:ps_3_0
ps_bright:ps_3_0 ps_blur:ps_3_0 ps_final:ps_3_0"
SCRIPT='export WINEDEBUG=-all; wineboot -i >/dev/null 2>&1; set -e; for e in '"$(echo $ENTRIES)"'; do n=${e%%:*}; p=${e##*:}; wine shc.exe visuals.hlsl $n $p $n.h k_$n >/dev/null || { echo "FAILED $n"; wine shc.exe visuals.hlsl $n $p $n.h k_$n; exit 1; }; done'
${DOCKER:-sudo -n docker} run --rm --cpuset-cpus=0-4 -v "$WORK:/w" -w /w "${SHC_IMAGE:-gta2-wine2510}" bash -c "$SCRIPT"
OUT=src/shaders/visuals_gen.h
{
  echo "// Generated by tools/build_shaders.sh from src/shaders/visuals.hlsl. Do not edit."
  echo "#pragma once"
  echo "#include <windows.h>"
  for e in $ENTRIES; do n=${e%%:*}; tail -n +2 "$WORK/$n.h"; done
} > "$OUT"
python3 -c "import shutil,sys; shutil.rmtree(sys.argv[1])" "$WORK"
echo "wrote $OUT ($(grep -c 'static const DWORD' $OUT) shaders)"
