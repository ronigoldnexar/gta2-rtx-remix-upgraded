#!/usr/bin/env python3
"""Coverage audit: what the ground views can show versus what has an upgraded
asset, per category and district, from the game's own data files.

    audit_assets.py <game dir> <assets-src dir> <repo dir> <out dir>

Writes <repo>/docs/asset-audit.md, <repo>/docs/asset-gaps.json and
<out>/audit_<category>.png contact sheets plus <out>/audit_summary.png.
Reads: *.sty (TILE, SPRX/SPRG, PALX/PPAL/PALB, CARI, RECY, OBJI), *.gmp (DMAP,
ANIM, ZONE, LGHT), the HD tile sets, the model manifest, the car catalog.
"""
import json, os, struct, sys
from collections import Counter, defaultdict
from PIL import Image, ImageDraw

GAME, SRC, REPO, OUT = sys.argv[1:5]
sys.path.insert(0, os.path.join(SRC, 'cars'))
import parse_sty  # noqa: E402

DISTRICTS = [('wil', 'Downtown'), ('bil', 'Residential'), ('ste', 'Industrial')]
W = H = 256
gaps = []
md = []


def sty_chunks(d):
    off, c = 6, {}
    while off + 8 <= len(d):
        tag = d[off:off + 4].decode('latin1'); size = struct.unpack_from('<I', d, off + 4)[0]
        c[tag] = (off + 8, size); off += 8 + size
    return c


def tile_image(st, c, i):
    """Tile i (0..991) as RGBA from the TILE pages (4x4 tiles of 64x64 per 256x256 page)."""
    d = st['d']; base = c['TILE'][0]
    page, k = divmod(i, 16); row, col = divmod(k, 4)
    pal = st['palette'](st['phys'](st['bases']['tile'] + i))
    img = Image.new('RGBA', (64, 64)); px = img.load()
    for y in range(64):
        o = base + page * 65536 + (row * 64 + y) * 256 + col * 64
        line = d[o:o + 64]
        for x, v in enumerate(line):
            if v == 0: px[x, y] = (0, 0, 0, 0)
            else:
                b, g, r, _ = pal[v]; px[x, y] = (r, g, b, 255)
    return img


def sprite_image(st, kind, i, remap=None):
    """Sprite i of a kind (car/ped/code_obj/map_obj) with its base palette or a remap."""
    order = ['car', 'ped', 'code_obj', 'map_obj', 'user', 'font']
    abs_i = sum(st['sprb'][:order.index(kind)]) + i
    if remap is None: virt = st['bases']['sprite'] + abs_i
    else: virt = st['bases'][kind + '_remap'] + remap
    return st['sprite_rgba'](abs_i, st['palette'](st['phys'](virt)))


def sheet(path, cells, cols=12, cell=80, label=True):
    rows = (len(cells) + cols - 1) // cols
    img = Image.new('RGBA', (cols * cell, max(1, rows) * (cell + 14)), (30, 30, 30, 255))
    dr = ImageDraw.Draw(img)
    for n, (im, text) in enumerate(cells):
        x, y = (n % cols) * cell, (n // cols) * (cell + 14)
        im = im.copy(); im.thumbnail((cell - 4, cell - 4), Image.NEAREST)
        img.paste(im, (x + 2, y + 2), im)
        if label: dr.text((x + 2, y + cell), text[:14], fill=(255, 255, 0, 255))
    img.save(path)


def gmp_load(path):
    d = open(path, 'rb').read(); off, c = 6, {}
    while off + 8 <= len(d):
        tag = d[off:off + 4].decode('latin1'); size = struct.unpack_from('<I', d, off + 4)[0]
        c[tag] = (off + 8, size); off += 8 + size
    base = c['DMAP'][0]; pool = base + W * H * 4
    words = struct.unpack_from('<I', d, pool)[0]; coldata = pool + 4
    nb_off = coldata + words * 4; nblocks = struct.unpack_from('<I', d, nb_off)[0]; bdata = nb_off + 4
    blocks = [struct.unpack_from('<HHHHHBB', d, bdata + i * 12) for i in range(nblocks)]
    columns = []
    for cell in range(W * H):
        wi = struct.unpack_from('<I', d, base + cell * 4)[0]; p = coldata + wi * 4
        height, offset = d[p], d[p + 1]
        idx = [struct.unpack_from('<I', d, p + 4 + i * 4)[0] for i in range(max(0, height - offset))]
        columns.append((offset, idx))
    o, sz = c['ANIM']; a = d[o:o + sz]; p = 0; anims = []
    while p + 6 <= len(a):
        b, rate, rep, n = struct.unpack_from('<HBBB', a, p); p += 6
        anims.append((b, rate, rep, list(struct.unpack_from(f'<{n}H', a, p)))); p += 2 * n
    o, sz = c['ZONE']; z = d[o:o + sz]; p = 0; zones = []
    while p + 6 <= len(z):
        typ, x, y, w, h, nl = struct.unpack_from('<6B', z, p); zones.append((typ, x, y, w, h, z[p + 6:p + 6 + nl].decode('latin1'))); p += 6 + nl
    o, sz = c['LGHT']; lights = [struct.unpack_from('<IHHHBBBBBB', d, o + i * 16) for i in range(sz // 16)]
    return blocks, columns, anims, zones, lights


# ---------------------------------------------------------------- tiles
md.append('# Asset coverage audit\n\nGenerated by `tools/audit_assets.py` from the game data, the HD tile sets, the model '
          'manifest and the car catalog. "Street level" means a face of a block within four levels of the '
          'lowest lid in its column, which is what a camera at eye height sees.\n')
md.append('## 1. Tiles (world textures)\n')
md.append('| district | tiles in style | used by the map | used at street level | with 512 px DDS | used but missing | street-level faces covered | animated tiles |\n|---|---|---|---|---|---|---|---|')
anim_notes = []
tile_cells = []
tile_missing_all = {}
for sty, name in DISTRICTS:
    st = parse_sty.parse(os.path.join(GAME, 'data', sty + '.sty')); c = sty_chunks(st['d'])
    blocks, columns, anims, zones, lights = gmp_load(os.path.join(GAME, 'data', sty + '.gmp'))
    use = Counter(); street = Counter()
    for offset, idx in columns:
        for i, bi in enumerate(idx):
            b = blocks[bi]; level = offset + i
            for face in b[:5]:
                t = face & 0x3FF
                if t == 0: continue
                use[t] += 1
                if i <= 4: street[t] += 1
    hd = {int(f[5:9]) for f in os.listdir(os.path.join(REPO, 'assets', 'textures_hd', sty)) if f.endswith('.dds')}
    missing = {t: street[t] for t in use if t not in hd}
    anim_tiles = {t for *_, ts in anims for t in ts} | {a[0] for a in anims}
    covered = sum(n for t, n in street.items() if t in hd) / max(1, sum(street.values()))
    anim_missing = sorted(t for t in anim_tiles if t not in hd)
    md.append(f'| {name} ({sty}) | 992 | {len(use)} | {len(street)} | {len(hd)} | {len(missing)} ({", ".join(str(t) for t in missing)}) | {covered*100:.1f}% | {len(anims)} groups, {len(anim_tiles)-len(anim_missing)}/{len(anim_tiles)} frames with DDS |')
    anim_notes.append((name, anims, anim_missing))
    for t in anim_missing:
        tile_cells.append((tile_image(st, c, t), f'{sty}{t} anim'))
        gaps.append(dict(category='tile', district=sty, id=t, name=f'animated tile frame {t}', sprite=None, street_faces=0,
                         priority='high', method='dump the TILE chunk directly (tools/audit_assets.py tile_image) and pack: animated water/neon alternate HD and 64 px frames otherwise'))
    tile_missing_all[sty] = sorted(missing.items(), key=lambda kv: -kv[1])
    for t, n in tile_missing_all[sty][:60]:
        tile_cells.append((tile_image(st, c, t), f'{sty}{t}:{n}'))
    for t, n in tile_missing_all[sty]:
        gaps.append(dict(category='tile', district=sty, id=t, name=f'tile {t}' + (' (animated)' if t in anim_tiles else ''),
                         sprite=None, street_faces=n, priority='high' if n > 200 else ('medium' if n > 20 else 'low'),
                         method='dump_tiles=1 with the level loaded, then tools/pack_textures_dds.py (ESRGAN+SD)'))
sheet(os.path.join(OUT, 'audit_tiles_missing.png'), tile_cells, cols=15, cell=72)
md.append('\nStatic tile coverage is complete apart from one tile per district (the sheet `out/audit_tiles_missing.png` '
          'shows them first). **The real gap is animation**: the ANIM groups (water, neon signs, flashing lights) cycle '
          'through frames that no block face references, so the dump never saw them and the game alternates a 512 px '
          'frame with 64 px ones, which flickers. Per district: ' +
          '; '.join(f'{n}: groups at tiles {", ".join(str(a[0]) for a in an)}, missing frames {", ".join(map(str, mi))}' for n, an, mi in anim_notes) +
          '. Fix: pack those frames straight from the style file (this script reads the TILE chunk) through the same ESRGAN/SD pipeline, '
          'keeping the frames of a group consistent (same seed, tiled together).\n')

# ---------------------------------------------------------------- cars
md.append('## 2. Vehicles\n')
cat = json.load(open(os.path.join(SRC, 'cars', 'catalog.json')))['cars']
man = json.load(open(os.path.join(REPO, 'assets', 'models', 'manifest.json')))
by_model = {int(k) for k in man['cars']['by_model']}
ai = {int(f[:3]) for f in os.listdir(os.path.join(SRC, 'cars', 'models3d')) if f.endswith('.glb')}
proc = {int(f[:3]) for f in os.listdir(os.path.join(SRC, 'cars', 'models_proc')) if f.endswith('.glb') and 'remap' not in f}
st = parse_sty.parse(os.path.join(GAME, 'data', 'wil.sty'))
recy = {sty: Counter(parse_sty.parse(os.path.join(GAME, 'data', sty + '.sty'))['recy']) for sty, _ in DISTRICTS}
md.append(f'CARI models: {len(cat)}. With a 3D model at run time: {len(by_model)} '
          f'({len(ai & by_model)} image-to-3D, {len(by_model - ai)} parametric). Traffic lists (RECY) per district name '
          f'{", ".join(f"{n}: {len([m for m in recy[s] if m != 255])}" for s, n in DISTRICTS)} models.\n')
md.append('| model | name | class | traffic (wil/bil/ste) | 3D model | note |\n|---|---|---|---|---|---|')
car_cells = []
for car in cat:
    m = car['model']; traffic = '/'.join(str(recy[s].get(m, 0)) for s, _ in DISTRICTS)
    has = 'AI' if m in ai and m in by_model else ('proc' if m in by_model else 'none')
    note = ''
    if 72 <= m <= 81: note = 'wreck (the game swaps the car sprite for it after an explosion)'
    elif car.get('shares_sprite_of_previous_model'): note = 'shares a sprite (dummy)'
    elif car['cls'] in ('train', 'trailer'): note = 'rail / trailer'
    if has != 'AI':
        md.append(f'| {m} | {car["name"]} | {car["cls"]} | {traffic} | {has} | {note} |')
    if has == 'none':
        car_cells.append((Image.open(os.path.join(SRC, 'cars', car['remaps'][0]['file'])), f'{m} {car["name"]}'))
        pri = 'high' if any(recy[s].get(m, 0) for s, _ in DISTRICTS) else ('medium' if 72 <= m <= 81 else 'low')
        gaps.append(dict(category='car', id=m, name=car['name'], sprite=os.path.join('assets-src/cars', car['remaps'][0]['file']),
                         priority=pri, method='wreck: derive from the intact model (crumpled, burnt paint) in tools/make_car_model.py; others: gen3d/car_pipeline.py'))
sheet(os.path.join(OUT, 'audit_cars_missing.png'), car_cells, cols=10, cell=96)
md.append('\nOnly rows without an image-to-3D model are listed (parametric stand-ins could be upgraded with gen3d/car_pipeline.py, they were skipped as trains/trailers/dummies); every traffic model has a model. '
          'Wrecks (72-81) are the visible gap: a car that explodes turns into a flat wreck sprite with no body. '
          'Remaps: one model per vehicle, repainted by the live sprite ratio (paint only), so all 668 remap variants are covered.\n')

# ---------------------------------------------------------------- pedestrians
md.append('## 3. Pedestrians\n')
nped = st['sprb'][1]; nrem = st['palb'][3]
peds = man.get('pedestrians', [])
md.append(f'Ped sprite frames in the style: {nped} (one shared body: walk, run, stand, fall, swim, burn, '
          f'shoot per weapon); ped remap palettes (the ped **types**): {nrem}. Avatars at run time: {len(peds)} '
          f'Rocketbox humans, chosen by a hash of the ped object, the player always the first.\n')
md.append('**Gap: ped type is ignored.** The game distinguishes police, SWAT, army, medics, firemen, gang members '
          '(Zaibatsu grey, Loonies green, Yakuza blue), prostitutes, Elvis impersonators and civilians only by the '
          'remap palette; the 3D people are all civilians, so a cop or a gang member is a random civilian in the '
          'ground views. The renderer already knows the sprite palette (`pal N` in its texture keys), so the fix is a '
          'palette-to-type table and per-type avatar sets (uniforms, gang colours) with the remap colour applied to '
          'the clothing material.\n')
ped_cells = [(sprite_image(st, 'ped', 0, r), f'remap {r}') for r in range(nrem)]
sheet(os.path.join(OUT, 'audit_ped_types.png'), ped_cells, cols=14, cell=64)
for r in range(nrem):
    gaps.append(dict(category='ped_type', id=r, name=f'ped remap palette {r}', sprite=f'out/audit_ped_types.png#{r}',
                     priority='high' if r < 12 else 'medium', method='palette->type table; Rocketbox uniform variants (police/medic/fire/army) + tinted clothing for gangs'))
# frames by animation state are also all mapped to walk/run/idle: note other states
md.append('Animation states with no 3D equivalent (the figure keeps idling): falling/lying dead, swimming, burning, '
          'getting in or out of a car, punching, shooting, being arrested. `out/audit_ped_frames.png` shows the frame set.\n')
sheet(os.path.join(OUT, 'audit_ped_frames.png'), [(sprite_image(st, 'ped', i), str(i)) for i in range(0, nped, 3)], cols=20, cell=48)
for state in ['dead/lying', 'swimming', 'burning', 'car entry/exit', 'punch', 'shoot', 'arrested']:
    gaps.append(dict(category='ped_anim', id=state, name=f'pedestrian animation: {state}', sprite=None, priority='medium',
                     method='merge Rocketbox clips (death, swim, punch, aim) by joint name in tools/import_assets.py; drive from the ped state bytes the log already reads'))

# ---------------------------------------------------------------- map objects
md.append('## 4. Map objects (OBJI, sprite base 5)\n')
nmap = st['sprb'][3]
mapped = {int(k.split(':')[1]) for k in man.get('objects', {}) if k.startswith('5:')}
missing_frames = [i for i in range(nmap) if i not in mapped]
md.append(f'Frames: {nmap} in 24 OBJI models; with a 3D model: {len(mapped)}; flat sprites left: {len(missing_frames)} '
          f'({", ".join(map(str, missing_frames))}). The scripts place almost only the bonus crates (model 25) and '
          'power-ups in single player, so most of these are rare in play; the ones left flat are litter, newspapers, '
          'oil patches, hubcaps and splinters, which read fine as decals.\n')
sheet(os.path.join(OUT, 'audit_mapobj_missing.png'), [(sprite_image(st, 'map_obj', i), str(i)) for i in missing_frames], cols=14, cell=64)
for i in missing_frames:
    gaps.append(dict(category='map_object', id=i, name=f'map object frame {i}', sprite=f'assets-src/objects/sprites_all/map_obj_{i:03d}.png',
                     priority='low', method='decal-style flat quad with the x4 sprite (litter/oil), or tools/gen_objects.py procedural'))

# ---------------------------------------------------------------- code objects
md.append('## 5. Code objects (sprite base 4)\n')
ncode = st['sprb'][2]
sizes = Counter()
code_cells = []
for i in range(ncode):
    im = sprite_image(st, 'code_obj', i)
    code_cells.append((im, str(i)))
sheet(os.path.join(OUT, 'audit_code_objects.png'), code_cells, cols=24, cell=48)
md.append(f'{ncode} frames: weapon and power-up pickups, phones, traffic lights, explosions, fire, smoke, blood, '
          'skid strips, bullets, water splashes, the helicopter, shadows and HUD arrows. The renderer rebuilds '
          'skids, blood, smoke, fire, lamps and gang emblems; the rest (pickups, phones, traffic lights, '
          'bus stops, the helicopter) are flat quads in the ground views. Sheet: `out/audit_code_objects.png`.\n')
for name, frames, method in [
        ('weapon pickups (rotating)', 'the 22-36 px icons', 'small 3D props: pistol, uzi, shotgun, rocket, flamethrower, grenade, armour, health, invulnerability (procedural or Poly Haven)'),
        ('phone boxes', 'the tall 18x35 frames', 'Poly Haven phone booth, placed at the sprite'),
        ('traffic lights / signals', 'pole + lamp frames', 'procedural pole with emissive lamps; the game animates the state'),
        ('explosion / fire / smoke', 'animated frames', 'billboard particle set with emissive (already partly rebuilt); keep'),
        ('helicopter', 'police helicopter frames', 'image-to-3D from the sprite (gen3d) with rotor animation')]:
    gaps.append(dict(category='code_object', id=name, name=name, sprite='out/audit_code_objects.png', priority='medium', method=method))

# ---------------------------------------------------------------- lights, props, zones
md.append('## 6. Lights, props and areas\n')
md.append('| district | map lamps (LGHT) | zones | notable areas |\n|---|---|---|---|')
for sty, name in DISTRICTS:
    blocks, columns, anims, zones, lights = gmp_load(os.path.join(GAME, 'data', sty + '.gmp'))
    names = sorted({z[5] for z in zones if z[5] not in ('cityinfo',)})
    md.append(f'| {name} | {len(lights)} (lamp post model at each) | {len(zones)} | {", ".join(names[:14])}{"..." if len(names) > 14 else ""} |')
md.append('\nRule-placed props: lamp (every map lamp), bin, bench, hydrant (pavement cells against buildings). '
          'Not represented: traffic signs, bus stops, parking meters, mailboxes, trees in parks (the "field" lid type '
          'covers grass, roofs and plazas, so trees need a zone or tile rule: grass tiles in park zones only), '
          'docks/cranes in Industrial, the elevated rail, water surfaces (animated tiles drawn flat; no reflection), '
          'bridges, fences (flat tiles with alpha, correct), window interiors (flat), roof detail (air-con units, '
          'vents, water towers exist only as tiles).\n')
for name, pri, method in [
        ('trees and shrubs in parks', 'high', 'Poly Haven trees, placed on grass tiles inside park zones (ZONE names) only'),
        ('traffic signs, bus stops, parking meters, mailboxes', 'medium', 'Poly Haven / procedural, placed by tile rule on pavement cells by the carriageway'),
        ('water surface', 'high', 'animated water tiles -> reflective plane with normal map and Remix translucency (tools/make_water_mod.py exists for Remix)'),
        ('Industrial docks, cranes, containers', 'medium', 'zone-rule props: cranes/containers on dock tiles (image-to-3D from the tiles)'),
        ('rooftop detail (vents, water towers, aircon)', 'low', 'tile-rule props on roof lids far from street level; only matters in BEV and chase from height'),
        ('window interiors / parallax', 'medium', 'Remix: emissive windows at night, interior cubemap material on window tiles'),
        ('weather', 'low', 'GTA2 has none; rain/wet roads as a Remix effect only'),
        ('time of day', 'medium', 'sky follows a fixed sun; wire [sky] follow_clock to Remix Plus time of day')]:
    gaps.append(dict(category='environment', id=name, name=name, sprite=None, priority=pri, method=method))

# ---------------------------------------------------------------- summary
md.append('## 7. Summary and priorities\n')
counts = Counter(g['category'] for g in gaps); pri = Counter(g['priority'] for g in gaps)
md.append('| category | gaps | high | medium | low |\n|---|---|---|---|---|')
for catg in counts:
    cs = [g for g in gaps if g['category'] == catg]
    md.append(f'| {catg} | {len(cs)} | {sum(g["priority"]=="high" for g in cs)} | {sum(g["priority"]=="medium" for g in cs)} | {sum(g["priority"]=="low" for g in cs)} |')
md.append('\nRecommended order for the fill agents:\n'
          '1. **Pedestrian types** (police, gangs, medics, firemen): visible in every street scene, breaks the game\'s own fiction when wrong.\n'
          '2. **Missing tiles**: a full dump per district fixes every remaining soft texture at once.\n'
          '3. **Water and park trees**: large areas of Residential and Industrial.\n'
          '4. **Wreck models** and **pedestrian death/car-entry animations**: every crash and fight shows them.\n'
          '5. **Pickups, phones, traffic lights, helicopter**: small but constant in play.\n'
          '6. Street furniture by rule, Industrial docks, rooftop detail, window interiors.\n')
os.makedirs(os.path.join(REPO, 'docs'), exist_ok=True)
open(os.path.join(REPO, 'docs', 'asset-audit.md'), 'w').write('\n'.join(md) + '\n')
json.dump(gaps, open(os.path.join(REPO, 'docs', 'asset-gaps.json'), 'w'), indent=1)

# summary image: bars per category
img = Image.new('RGB', (900, 60 + 34 * len(counts)), (25, 25, 30)); dr = ImageDraw.Draw(img)
dr.text((10, 10), 'Asset gaps by category (high / medium / low priority)', fill=(255, 255, 255))
y = 40
for catg in counts:
    cs = [g for g in gaps if g['category'] == catg]; x = 220
    dr.text((10, y + 8), f'{catg} ({len(cs)})', fill=(220, 220, 220))
    for p, colr in (('high', (220, 70, 70)), ('medium', (230, 170, 60)), ('low', (90, 160, 90))):
        n = sum(g['priority'] == p for g in cs); wbar = min(650, n * 6)
        if n: dr.rectangle([x, y + 4, x + wbar, y + 26], fill=colr); dr.text((x + 3, y + 8), str(n), fill=(0, 0, 0)); x += wbar + 4
    y += 34
img.save(os.path.join(OUT, 'audit_summary.png'))
print('gaps', len(gaps), dict(counts))
