#!/usr/bin/env python3
"""FIX-WORLD-7 (pm26-bil-third-wall-base-stair-step-blocky-band): the street views' lit-window glow
(src/renderer.cpp MakeWindowGlow) took any dark bluish run of texels for glass, so ~180 tiles per
district glowed (fans, girders, pipes, the grime wall 118 that made the stair-stepped band). The
window and shop-window boxes the facade pass grounded on every wall tile (tools/facade_boxes.json,
docs/facade-depth.md) now say where the glass is. This writes them as a C++ table:

    python3 tools/facade_window_table.py tools/facade_boxes.json src/facade_windows.inc

Coordinates only (64 px tile units, rounded outward), no art."""
import json, math, sys

src, out = sys.argv[1], sys.argv[2]
boxes = json.load(open(src))
rows, styles, tiles = [], set(), set()
for key in sorted(boxes, key=lambda k: (k.split(":")[0], int(k.split(":")[1]))):
    style, tile = key.split(":"); tile = int(tile)
    styles.add(style)
    seen = set()
    for b in boxes[key]["boxes"]:
        if b["label"] not in ("window", "shop window"):
            continue
        x0, y0, x1, y1 = b["box"]
        r = (max(0, math.floor(x0)), max(0, math.floor(y0)), min(64, math.ceil(x1)), min(64, math.ceil(y1)))
        if r[2] - r[0] < 3 or r[3] - r[1] < 3 or r in seen:
            continue
        seen.add(r); tiles.add((style, tile))
        rows.append(f'    {{"{style}", {tile}, {r[0]}, {r[1]}, {r[2]}, {r[3]}}},')
with open(out, "w") as f:
    f.write("// Generated by tools/facade_window_table.py from tools/facade_boxes.json (do not edit).\n")
    f.write(f"// {len(rows)} window/shop-window boxes on {len(tiles)} wall tiles; styles listed are covered whole:\n")
    f.write("// a wall tile of one of them with no box has no window.\n")
    f.write("struct FacadeWindowBox { const char* style; int tile; int x0, y0, x1, y1; };\n")
    f.write("static const FacadeWindowBox kFacadeWindowBoxes[] = {\n" + "\n".join(rows) + "\n};\n")
    f.write("static const char* const kFacadeWindowStyles[] = {" + ", ".join(f'"{s}"' for s in sorted(styles)) + "};\n")
print(len(rows), "boxes on", len(tiles), "tiles;", sorted(styles))
