#!/usr/bin/env python3
"""FIX-WORLD-7 (pm26-bil-third-wall-base-stair-step-blocky-band): the street views' lit-window glow
(src/renderer.cpp MakeWindowGlow) took any dark bluish run of texels for glass, so ~180 tiles per
district glowed (fans, girders, pipes, the grime wall 118 that made the stair-stepped band). The
window and shop-window boxes the facade pass grounded on every wall tile (tools/facade_boxes.json,
docs/facade-depth.md) now say where the glass is. This writes them as a C++ table:

    python3 tools/facade_window_table.py tools/facade_boxes.json src/facade_windows.inc

Coordinates only (64 px tile units, rounded outward), no art."""
import json, math, sys

# Tiles whose "shop window" box is not glass the glow/sky may paint: the pane mask is the 64 px art's
# dark-blue runs, so over a door it lays blocky sky/glow patches on the leaves (FIX-WORLD-8 pm6: the
# Altamount arched double door read as a smeared ghost). Their photo tile paints its own glass.
NOT_GLASS = {("wil", 538)}   # pm6-arched-doors-smeared-ghost-texture (tools/arch_door_tile.py)
# qav19 (FIX-WORLD-14): the wil shop front 231 (striped shutter, oval light, a dark storefront below) took a
# flat warm glow over its whole storefront box at dusk and night: an ochre slab with black rectangles where
# the 64 px art is not dark enough to count as pane. It stays the steel-grey front it is by day, darker.
NOT_GLASS |= {("wil", 231)}
# qav60 (FIX-WORLD-16): wil 428, the ground-floor wall of the green pilastered block (wil 40,168-171), is plain
# green panels between pilasters, no glass at all; the facade pass boxed the panels as windows, so at night they
# filled with flat beige blocks stepped at the 64 px grid. The floor above (416/418) keeps its real windows.
NOT_GLASS |= {("wil", 428)}
# qav39 (FIX-WORLD-16): bil 658, the top course of the bil towers (dark metal cornice frieze over pale brick), has no
# glass; its one "window" box is the frieze, so at night the glow filled the frieze's dark texels: day-bright tan
# caps with ragged 64 px-stepped edges over near-black walls.
NOT_GLASS |= {("bil", 658)}
# FIX-WORLD-17 (fw17-bil-107, the ste glow audit): wall tiles whose box sits on art that is not glass, each found by
# simulating the glow rule on the 64 px tile and confirmed with a same-session [devtools] window_glow on/off pair at 23:00:
# bil 107, an arched stone double doorway (the stone and door frames round its pale doors filled with a flat beige slab);
# ste 56, a dark truss frieze over a shutter (a bright tan band the width of the wall); ste 727, a ribbed dark object in a
# tower's recess (a tan figure-shaped blob); ste 480, a window whose panes are painted light (only the dark lintel bar over
# them lit, a tan line); bil 622, a kiosk's panelled door with a plaque (the door lit as a tan slab). (bil 310, the
# FIX-WORLD-16 suspect, never glows: it is also a lid, and lid tiles get no glow.)
NOT_GLASS |= {("bil", 107), ("bil", 622), ("ste", 56), ("ste", 727), ("ste", 480)}

src, out = sys.argv[1], sys.argv[2]
boxes = json.load(open(src))
rows, styles, tiles = [], set(), set()
for key in sorted(boxes, key=lambda k: (k.split(":")[0], int(k.split(":")[1]))):
    style, tile = key.split(":"); tile = int(tile)
    styles.add(style)
    if (style, tile) in NOT_GLASS:
        continue
    seen = set()
    for b in boxes[key]["boxes"]:
        if b["label"] not in ("window", "shop window"):
            continue
        x0, y0, x1, y1 = b["box"]
        r = (max(0, math.floor(x0)), max(0, math.floor(y0)), min(64, math.ceil(x1)), min(64, math.ceil(y1)))
        if r[2] - r[0] < 3 or r[3] - r[1] < 3 or r in seen:
            continue
        seen.add(r); tiles.add((style, tile))
        rows.append(f'    {{"{style}", {tile}, {r[0]}, {r[1]}, {r[2]}, {r[3]}}},')
with open(out, "w") as f:
    f.write("// Generated by tools/facade_window_table.py from tools/facade_boxes.json (do not edit).\n")
    f.write(f"// {len(rows)} window/shop-window boxes on {len(tiles)} wall tiles; styles listed are covered whole:\n")
    f.write("// a wall tile of one of them with no box has no window.\n")
    f.write("struct FacadeWindowBox { const char* style; int tile; int x0, y0, x1, y1; };\n")
    f.write("static const FacadeWindowBox kFacadeWindowBoxes[] = {\n" + "\n".join(rows) + "\n};\n")
    f.write("static const char* const kFacadeWindowStyles[] = {" + ", ".join(f'"{s}"' for s in sorted(styles)) + "};\n")
print(len(rows), "boxes on", len(tiles), "tiles;", sorted(styles))
