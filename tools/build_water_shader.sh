#!/usr/bin/env bash
# Compiles src/shaders/water.hlsl into src/shaders/water_gen.h (shader model 3 bytecode as
# DWORD arrays). The water shader is loop-free, so Wine 9's d3dcompiler in the gta2-remixbox
# image builds it (tools/build_shaders.sh needs Wine 10 for visuals.hlsl's loops).
#   tools/build_water_shader.sh       (from the repository root; SHC_IMAGE overrides the image)
set -e
cd "$(dirname "$0")/.."
WORK=$(mktemp -d)
i686-w64-mingw32-g++ -O1 -static -o "$WORK/shc.exe" tools/shc.cpp
cp src/shaders/water.hlsl "$WORK/"
ENTRIES="vs_water:vs_3_0 ps_water:ps_3_0"
SCRIPT='export WINEDEBUG=-all; wineboot -i >/dev/null 2>&1; set -e; for e in '"$(echo $ENTRIES)"'; do n=${e%%:*}; p=${e##*:}; wine shc.exe water.hlsl $n $p $n.h k_$n $n.txt >/dev/null || { echo "FAILED $n"; wine shc.exe water.hlsl $n $p $n.h k_$n; exit 1; }; done'
${DOCKER:-sudo -n docker} run --rm --cpuset-cpus=0-4 -v "$WORK:/w" -w /w "${SHC_IMAGE:-gta2-remixbox}" bash -c "$SCRIPT"
# Wine's GLSL path declares r0-r31 only (see tools/build_shaders.sh).
for e in $ENTRIES; do n=${e%%:*}; m=$(grep -oE '\br[0-9]+' "$WORK/$n.txt" | tr -d r | sort -n | tail -1)
  echo "$n: highest temporary r$m"; [ "${m:-0}" -le 31 ] || { echo "FAILED $n uses r$m (max r31)"; exit 1; }; done
OUT=src/shaders/water_gen.h
{
  echo "// Generated by tools/build_water_shader.sh from src/shaders/water.hlsl. Do not edit."
  echo "#pragma once"
  echo "#include <windows.h>"
  for e in $ENTRIES; do n=${e%%:*}; tail -n +2 "$WORK/$n.h"; done
} > "$OUT"
python3 -c "import shutil,sys; shutil.rmtree(sys.argv[1])" "$WORK"
echo "wrote $OUT ($(grep -c 'static const DWORD' $OUT) shaders)"
